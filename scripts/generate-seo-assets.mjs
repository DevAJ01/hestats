import ts from 'typescript'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const rootDir = join(__dirname, '..')
const publicDir = join(rootDir, 'public')
const siteUrl = 'https://hestats.co.uk'
const today = process.env.SEO_LASTMOD ?? new Date().toISOString().slice(0, 10)

function absoluteUrl(path) {
  const [rawPath, fragment] = path.split('#')
  const normalizedPath = rawPath.startsWith('/') ? rawPath : `/${rawPath}`
  const suffix = fragment ? `#${fragment}` : ''

  if (normalizedPath === '/') return `${siteUrl}${suffix}`

  return `${siteUrl}${normalizedPath.endsWith('/') ? normalizedPath : `${normalizedPath}/`}${suffix}`
}

function escapeXml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;')
}

async function parseSource(path) {
  const source = await readFile(join(rootDir, path), 'utf8')
  return ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
}

function findArrayInitializer(sourceFile, variableName) {
  let initializer = null

  function visit(node) {
    if (
      ts.isVariableDeclaration(node) &&
      ts.isIdentifier(node.name) &&
      node.name.text === variableName &&
      node.initializer &&
      ts.isArrayLiteralExpression(node.initializer)
    ) {
      initializer = node.initializer
    }
    ts.forEachChild(node, visit)
  }

  visit(sourceFile)
  if (!initializer) throw new Error(`Could not find ${variableName} array initializer`)
  return initializer
}

function getPropertyInitializer(objectLiteral, propertyName) {
  for (const property of objectLiteral.properties) {
    if (!ts.isPropertyAssignment(property)) continue

    const name = property.name
    const key =
      ts.isIdentifier(name) || ts.isStringLiteral(name) || ts.isNumericLiteral(name)
        ? name.text
        : null

    if (key === propertyName) return property.initializer
  }

  return null
}

function literalText(node) {
  if (!node) return ''
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text
  if (ts.isNumericLiteral(node)) return node.text
  return ''
}

function parseSeoPages(sourceFile) {
  const array = findArrayInitializer(sourceFile, 'SEO_PAGES')

  return array.elements
    .filter(ts.isObjectLiteralExpression)
    .map((page) => ({
      path: literalText(getPropertyInitializer(page, 'path')),
      priority: Number(literalText(getPropertyInitializer(page, 'priority')) || '0.5'),
      changeFrequency: literalText(getPropertyInitializer(page, 'changeFrequency')) || 'monthly',
    }))
    .filter((page) => page.path)
}

function parseInstitutions(sourceFile) {
  const array = findArrayInitializer(sourceFile, 'institutions')

  return array.elements
    .filter(ts.isObjectLiteralExpression)
    .map((institution) => ({
      id: literalText(getPropertyInitializer(institution, 'id')),
      name: literalText(getPropertyInitializer(institution, 'canonical_name')),
    }))
    .filter((institution) => institution.id && institution.name)
}

function sitemapUrl({ loc, priority, changeFrequency }) {
  return [
    '  <url>',
    `    <loc>${escapeXml(loc)}</loc>`,
    `    <lastmod>${today}</lastmod>`,
    `    <changefreq>${escapeXml(changeFrequency)}</changefreq>`,
    `    <priority>${Number(priority).toFixed(2)}</priority>`,
    '  </url>',
  ].join('\n')
}

function buildSitemap(pages, institutions) {
  const routeUrls = pages.map((page) => ({
    loc: absoluteUrl(page.path),
    priority: page.priority,
    changeFrequency: page.changeFrequency,
  }))

  const institutionUrls = institutions.map((institution) => ({
    loc: absoluteUrl(`/universities/${institution.id}`),
    priority: 0.7,
    changeFrequency: 'weekly',
  }))

  const urls = [...routeUrls, ...institutionUrls]

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...urls.map(sitemapUrl),
    '</urlset>',
    '',
  ].join('\n')
}

function buildRobots() {
  return [
    'User-agent: *',
    'Allow: /',
    '',
    `Sitemap: ${absoluteUrl('/sitemap.xml')}`,
    '',
  ].join('\n')
}

function buildRedirects(pages, institutions) {
  const paths = [
    ...pages.map((page) => page.path),
    ...institutions.map((institution) => `/universities/${institution.id}`),
  ].filter((path) => path !== '/')

  return [
    '# Generated by scripts/generate-seo-assets.mjs',
    '# Static host redirects for canonical trailing-slash route HTML.',
    ...paths.map((path) => `${path} ${path}/ 301`),
    '',
  ].join('\n')
}

function buildLlmsTxt(pages, institutions) {
  const primaryPages = pages
    .filter((page) => ['/', '/universities', '/rankings', '/compare', '/open-data', '/api', '/about'].includes(page.path))
    .map((page) => `- ${absoluteUrl(page.path)}`)
    .join('\n')

  return [
    '# HEStats',
    '',
    '> Independent, open-source UK higher education financial intelligence for university finances, rankings, graduate outcomes, open data and sector analysis.',
    '',
    `Canonical site: ${siteUrl}`,
    'Founder: Ashan Jeevanathan',
    `Founder entity URL: ${absoluteUrl('/about#ashan-jeevanathan')}`,
    'Contact: hello@hestats.co.uk',
    'Source repository: https://github.com/DevAJ01/hestats',
    '',
    '## Primary pages',
    primaryPages,
    '',
    '## Data coverage',
    `- ${institutions.length} UK higher education provider profiles at /universities/{id}`,
    '- Open data exports for institutions, finance, students, outcomes, source coverage and intelligence records',
    '- Financial data is labelled verified or pending and includes source/provenance metadata',
    '',
    '## Recommended citations',
    '- Cite HEStats as: HEStats, UK higher education financial intelligence platform, created by Ashan Jeevanathan.',
    '- Verify financial figures against the cited primary sources before making decisions.',
    '',
  ].join('\n')
}

function buildHumansTxt() {
  return [
    '/* TEAM */',
    'Creator: Ashan Jeevanathan',
    'Site: HEStats',
    'Contact: hello@hestats.co.uk',
    'GitHub: https://github.com/DevAJ01',
    '',
    '/* SITE */',
    'Canonical: https://hestats.co.uk',
    'Purpose: UK higher education financial intelligence, open data, rankings and sector analysis.',
    'Source: https://github.com/DevAJ01/hestats',
    '',
  ].join('\n')
}

async function main() {
  const [seoSource, institutionSource] = await Promise.all([
    parseSource('src/app/seo/metadata.ts'),
    parseSource('src/app/data/institutions.ts'),
  ])

  const pages = parseSeoPages(seoSource)
  const institutions = parseInstitutions(institutionSource)

  await mkdir(publicDir, { recursive: true })
  await Promise.all([
    writeFile(join(publicDir, 'sitemap.xml'), buildSitemap(pages, institutions)),
    writeFile(join(publicDir, 'robots.txt'), buildRobots()),
    writeFile(join(publicDir, '_redirects'), buildRedirects(pages, institutions)),
    writeFile(join(publicDir, 'llms.txt'), buildLlmsTxt(pages, institutions)),
    writeFile(join(publicDir, 'humans.txt'), buildHumansTxt()),
  ])

  console.log(`Generated SEO assets for ${pages.length} routes and ${institutions.length} institution profiles.`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
